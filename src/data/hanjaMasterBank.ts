// Helper to find radical name and default stroke
function getRadicalMeta(radicalChar: string) {
  const found = KANGXI_RADICALS.find((r) => r.radical === radicalChar);
  return {
    name: found ? found.name : '부수',
    strokes: found ? found.strokes : 4,
  };
}

