// Merge with the full assigned Hanja bank
import { generateFullHanjaBank } from './hanjaMasterBank';

function buildCompleteHanjaDatabase(): HanjaItem[] {
  const existingHanjaSet = new Set<string>();
  const combined: HanjaItem[] = [];

  // Add rich handcrafted items first
  CORE_HANJA_DATA.forEach((item) => {
    if (!existingHanjaSet.has(item.hanja)) {
      existingHanjaSet.add(item.hanja);
      combined.push(item);
    }
  });

  // Add master bank items
  const masterList = generateFullHanjaBank();
  masterList.forEach((item) => {
    if (!existingHanjaSet.has(item.hanja)) {
      existingHanjaSet.add(item.hanja);
      combined.push(item);
    }
  });

  return combined;
}

export const HANJA_DATA: HanjaItem[] = buildCompleteHanjaDatabase();
